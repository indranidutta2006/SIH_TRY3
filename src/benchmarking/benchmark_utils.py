# -*- coding: utf-8 -*-
"""Utility functions for Phase 3 benchmarking.

This module provides:
- A canonical ``decode_and_repair`` function used by all meta‑heuristic solvers.
- ``BenchmarkEvaluationCache`` ensuring per‑run isolation of cached evaluations.
- Helper to compute a deterministic *scenario fingerprint* covering every
  objective‑affecting variable.
- Simple reliability validator enforcing ``simulated_delay_count == total_voyages``.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from typing import Any, Callable, Final, Mapping, Sequence, Tuple

import numpy as np

# ---------------------------------------------------------------------------
# Canonical decoder & repair
# ---------------------------------------------------------------------------

SUPPORTED_FUEL_CHOICES: Final[Tuple[str, ...]] = (
    "Diesel",
    "LNG",
    "Methanol",
    "Hydrogen",
    "Ammonia",
)  # five‑fuel benchmark

def _integer_conversion(x: np.ndarray) -> np.ndarray:
    """Round continuous variables that must be integral.

    Currently only ``fuel_type`` indices are required to be integers.  The
    caller is responsible for applying this to the correct slots.
    """
    return np.rint(x).astype(float)

def _fleet_count_reconciliation(assignments: Sequence[Any], x: np.ndarray) -> np.ndarray:
    """Ensure the decision vector length matches the number of assigned voyages.

    The vector is expected to contain ``2`` values per assigned voyage: ``speed``
    and ``fuel_type``.  If the vector is longer, excess entries are truncated; if
    it is shorter, missing entries are filled with the lower bound (10 knots) and
    the first fuel (index 0).
    """
    n_voyages = len([a for a in assignments if getattr(a, "assigned", False)])
    expected_len = 2 * n_voyages
    if x.size == expected_len:
        return x
    if x.size > expected_len:
        return x[:expected_len]
    # Pad with defaults (speed=10, fuel=0)
    pad = np.full(expected_len - x.size, 0.0, dtype=float)
    # First speed entry defaults to lower bound (10 knots); we handle that later in bounds.
    return np.concatenate([x, pad])

def _five_fuel_allocation(x: np.ndarray) -> np.ndarray:
    """Clamp the fuel index to the five‑fuel set.

    The second entry of each ``(speed, fuel)`` pair is interpreted as an index
    into ``SUPPORTED_FUEL_CHOICES``.  Values outside ``[0, len-1]`` are clipped.
    """
    # Every odd position (1‑based) corresponds to a fuel index.
    fuel_indices = x[1::2]
    clipped = np.clip(fuel_indices, 0, len(SUPPORTED_FUEL_CHOICES) - 1)
    x[1::2] = clipped
    return x

def _budget_validation(lb: np.ndarray, ub: np.ndarray, x: np.ndarray) -> Tuple[np.ndarray, bool]:
    """Clip the vector to the provided bounds and report if any clipping occurred.

    Returns the clipped vector and a boolean ``changed`` flag.
    """
    clipped = np.clip(x, lb, ub)
    changed = not np.array_equal(clipped, x)
    return clipped, changed

def _repair_distance(original: np.ndarray, repaired: np.ndarray) -> float:
    """L2 distance between the original and repaired decision vectors.
    """
    return float(np.linalg.norm(original - repaired))

def decode_and_repair(
    x: np.ndarray,
    assignments: Sequence[Any],
    lb: np.ndarray,
    ub: np.ndarray,
) -> Tuple[np.ndarray, float]:
    """Canonical decoder used by **all** meta‑heuristic solvers.

    The function performs the following steps (in order):

    1. **Integer conversion** – round values that should be integral.
    2. **Fleet count reconciliation** – ensure the vector length matches the
       number of assigned voyages.
    3. **Five‑fuel allocation** – clamp fuel‑type indices to the allowed five
       fuels.
    4. **Budget validation** – clip to the problem bounds.
    5. **Repair distance** – compute the L2 distance between the input and the
       repaired vector (used for reporting).

    Parameters
    ----------
    x: np.ndarray
        Raw decision vector supplied by the optimizer.
    assignments: Sequence[Any]
        ``FleetAssignment`` objects generated by the scheduler.
    lb, ub: np.ndarray
        Lower and upper bound arrays (flattened per‑parameter).

    Returns
    -------
    tuple[np.ndarray, float]
        ``(repaired_vector, repair_distance)``
    """
    original = x.copy()
    # Step 1 – integer conversion (fuel indices will be rounded later).
    x = _integer_conversion(x)
    # Step 2 – ensure correct dimensionality.
    x = _fleet_count_reconciliation(assignments, x)
    # Step 3 – clamp fuel indices to the five‑fuel set.
    x = _five_fuel_allocation(x)
    # Step 4 – enforce bounds.
    x, _ = _budget_validation(lb, ub, x)
    # Step 5 – compute repair distance.
    distance = _repair_distance(original, x)
    return x, distance

# ---------------------------------------------------------------------------
# Benchmark evaluation cache
# ---------------------------------------------------------------------------

@dataclass
class BenchmarkEvaluationCache:
    """A per‑run cache for objective evaluations.

    The cache key is a deterministic fingerprint consisting of the flattened
    decision vector **and** a JSON‑encoded *scenario fingerprint* (see
    :func:`scenario_fingerprint`).  The value is the computed objective ``float``.
    """

    _store: dict[int, float] = field(default_factory=dict)

    def _hash_key(self, x: np.ndarray, scenario_fp: str) -> int:
        # Combine the binary representation of the vector with the scenario hash.
        hasher = hashlib.sha256()
        hasher.update(x.tobytes())
        hasher.update(scenario_fp.encode("utf-8"))
        # Use the first 8 bytes as an integer key for fast dict lookup.
        return int.from_bytes(hasher.digest()[:8], "big", signed=False)

    def get(self, x: np.ndarray, scenario_fp: str) -> Tuple[bool, float | None]:
        """Return ``(hit, value)``.  ``hit`` is ``True`` if the key is cached.
        """
        key = self._hash_key(x, scenario_fp)
        if key in self._store:
            return True, self._store[key]
        return False, None

    def set(self, x: np.ndarray, scenario_fp: str, value: float) -> None:
        key = self._hash_key(x, scenario_fp)
        self._store[key] = value

    # Metrics --------------------------------------------------------------
    @property
    def n_hits(self) -> int:
        return sum(1 for _ in self._store.values())  # placeholder—actual hits tracked elsewhere

    # The caller should maintain separate counters for hits/misses.

# ---------------------------------------------------------------------------
# Scenario fingerprinting
# ---------------------------------------------------------------------------

def scenario_fingerprint(context: Mapping[str, Any]) -> str:
    """Return a deterministic JSON string that uniquely identifies a scenario.

    The fingerprint includes all fields that affect the objective function.  It
    deliberately avoids using a simple ``scenario_id``.
    """
    # Define the deterministic order of keys expected by the benchmark.
    relevant_keys = [
        "cargo_demand",
        "route_distance",
        "deadline",
        "carbon_price",
        "budget",
        "weather",
        "vessel_class",
        "service_level",
        "fuel_prices",
        "routes",
        "weights",
        "regulatory_parameters",
    ]
    # Extract and sort sub‑objects to ensure stable representation.
    filtered: dict[str, Any] = {k: context.get(k) for k in relevant_keys}
    # ``json.dumps`` with ``sort_keys=True`` guarantees deterministic ordering.
    return json.dumps(filtered, sort_keys=True, ensure_ascii=False)

# ---------------------------------------------------------------------------
# Reliability evaluator
# ---------------------------------------------------------------------------

def verify_reliability(simulated_delay_count: int, total_voyages: int) -> None:
    """Raise ``ValueError`` if the reliability cardinality contract is violated.
    """
    if simulated_delay_count != total_voyages:
        raise ValueError(
            f"Reliability contract broken: simulated_delay_count ({simulated_delay_count}) "
            f"!= total_voyages ({total_voyages})"
        )

